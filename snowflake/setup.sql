-- Snowflake Setup Script for Patient360 Copilot
-- Run this script as an ACCOUNTADMIN or a role with equivalent privileges.

CREATE DATABASE IF NOT EXISTS HEALTH_DB;
USE DATABASE HEALTH_DB;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS CURATED;

-- 1. Create File Formats & Stages
USE SCHEMA RAW;

CREATE OR REPLACE FILE FORMAT my_csv_format
  TYPE = CSV
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  NULL_IF = ('NULL', 'null')
  EMPTY_FIELD_AS_NULL = true
  FIELD_OPTIONALLY_ENCLOSED_BY = '0x22';

CREATE OR REPLACE STAGE structured_data_stage
  FILE_FORMAT = my_csv_format
  DIRECTORY = (ENABLE = TRUE);

CREATE OR REPLACE STAGE unstructured_data_stage
  DIRECTORY = (ENABLE = TRUE);

-- 2. Create Structured Tables
CREATE OR REPLACE TABLE PATIENTS (
    PATIENT_ID VARCHAR,
    FIRST_NAME VARCHAR,
    LAST_NAME VARCHAR,
    DOB DATE,
    GENDER VARCHAR,
    ADDRESS VARCHAR,
    CITY VARCHAR,
    STATE VARCHAR,
    ZIP VARCHAR,
    PHONE VARCHAR
);

CREATE OR REPLACE TABLE ENCOUNTERS (
    ENCOUNTER_ID VARCHAR,
    PATIENT_ID VARCHAR,
    ENCOUNTER_DATE DATE,
    PROVIDER VARCHAR,
    DIAGNOSIS_CODE VARCHAR,
    DIAGNOSIS_DESC VARCHAR
);

CREATE OR REPLACE TABLE MEDICATIONS (
    MEDICATION_ID VARCHAR,
    PATIENT_ID VARCHAR,
    ENCOUNTER_ID VARCHAR,
    PRESCRIBED_DATE DATE,
    DRUG_NAME VARCHAR,
    FREQUENCY VARCHAR,
    STATUS VARCHAR
);

CREATE OR REPLACE TABLE CLAIMS (
    CLAIM_ID VARCHAR,
    PATIENT_ID VARCHAR,
    ENCOUNTER_ID VARCHAR,
    SERVICE_DATE DATE,
    TOTAL_AMOUNT FLOAT,
    PAYER VARCHAR,
    STATUS VARCHAR
);

CREATE OR REPLACE TABLE DOCUMENT_METADATA (
    DOCUMENT_ID VARCHAR,
    PATIENT_ID VARCHAR,
    ENCOUNTER_ID VARCHAR,
    DOCUMENT_TYPE VARCHAR,
    FILE_NAME VARCHAR,
    CREATED_DATE DATE
);

-- 3. Dynamic Data Masking (Governance demo)
CREATE OR REPLACE MASKING POLICY phone_mask AS (val string) RETURNS string ->
  CASE
    WHEN CURRENT_ROLE() IN ('CLINICIAN_ROLE', 'SYSADMIN', 'ACCOUNTADMIN') THEN val
    ELSE '***-***-****'
  END;

ALTER TABLE PATIENTS MODIFY COLUMN PHONE SET MASKING POLICY phone_mask;
